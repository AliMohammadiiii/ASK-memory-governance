#!/usr/bin/env python3
"""Build the final evaluation freeze manifest from exact file bytes."""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import subprocess
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]

FROZEN_FILES = (
    "benchmarks/mgp6/data/mgp6_v2.jsonl",
    "benchmarks/mgp6/metrics_mgp6.py",
    "configs/models/openrouter_qwen_gemma.yaml",
    "configs/release/final.yaml",
    "FINAL_EVALUATION_PROTOCOL.md",
    "FINAL_ANALYSIS_PLAN.md",
    "FINAL_METRIC_DEFINITIONS.md",
    "FINAL_RUN_MATRIX.yaml",
    "scripts/build_stratified_slice.py",
    "scripts/evaluation/run_longmemeval_final.sh",
    "deploy/run_colab_modal_range.sh",
    "scripts/run_vllm_cascade.py",
    "scripts/run_baseline.py",
    "scripts/verify_homogeneous_run.py",
    "scripts/analysis/check_controller_accuracy_gate.py",
    "scripts/analysis/judge_audit.py",
    "src/ask/baselines/embeddings.py",
    "src/ask/controller/computation.py",
    "src/ask/eval/longmemeval.py",
    "src/ask/eval/merge.py",
    "src/ask/inference/openai_compatible.py",
    "src/ask/pipeline/orchestrator.py",
)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def prompt_bundle() -> tuple[list[str], str]:
    paths = sorted(
        path
        for root in (REPO / "prompts", REPO / "src/ask/baselines/prompts")
        for path in root.rglob("*")
        if path.is_file() and "__pycache__" not in path.parts
    )
    digest = hashlib.sha256()
    relpaths: list[str] = []
    for path in paths:
        rel = path.relative_to(REPO).as_posix()
        relpaths.append(rel)
        digest.update(rel.encode() + b"\0" + path.read_bytes() + b"\0")
    return relpaths, digest.hexdigest()


def external_record(path: Path, *, include_ids: bool) -> dict[str, Any]:
    record: dict[str, Any] = {
        "sha256": sha256_file(path),
        "size_bytes": path.stat().st_size,
    }
    if include_ids:
        ids: list[str] = []
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                if line.strip():
                    row = json.loads(line)
                    ids.append(str(row.get("session_id")))
        if any(value == "None" for value in ids) or len(ids) != len(set(ids)):
            raise SystemExit("external slice has missing or duplicate session_ids")
        record["n_rows"] = len(ids)
        record["session_ids_sha256"] = hashlib.sha256("\n".join(ids).encode()).hexdigest()
    return record


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=REPO / "artifacts/manifests/freeze_hashes.json",
    )
    parser.add_argument("--external-slice", type=Path)
    parser.add_argument("--external-full-source", type=Path)
    args = parser.parse_args()

    files = {rel: sha256_file(REPO / rel) for rel in FROZEN_FILES}
    prompt_files, prompt_hash = prompt_bundle()
    try:
        git_head = subprocess.check_output(
            ["git", "-C", str(REPO), "rev-parse", "HEAD"], text=True
        ).strip()
        git_dirty = bool(
            subprocess.check_output(
                ["git", "-C", str(REPO), "status", "--porcelain"], text=True
            ).strip()
        )
    except (OSError, subprocess.CalledProcessError):
        git_head, git_dirty = None, None

    external: dict[str, Any] = {}
    if args.external_slice:
        external["longmemeval_m_strat30_seed0"] = external_record(
            args.external_slice, include_ids=True
        )
    if args.external_full_source:
        external["longmemeval_m_full_source"] = external_record(
            args.external_full_source, include_ids=False
        )

    payload = {
        "manifest": "freeze_hashes",
        "freeze_version": "final-2.0",
        "algorithm": "sha256",
        "computed_at_utc": dt.datetime.now(dt.UTC).isoformat(),
        "git_head": git_head,
        "git_dirty": git_dirty,
        "files": files,
        "prompts_combined": {
            "method": "sorted repo-relative path + NUL + bytes + NUL",
            "files": prompt_files,
            "sha256": prompt_hash,
        },
        "external_inputs_not_redistributed": external,
        "note": (
            "Generated by scripts/release/build_freeze_manifest.py. External "
            "records contain hashes and sizes only, never local paths or data."
        ),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.out.with_suffix(args.out.suffix + ".tmp")
    tmp.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    tmp.replace(args.out)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
