#!/usr/bin/env bash
set -euo pipefail

# Final high-recall HF profile for one A100 40GB. It runs two 7B fp16
# subprocesses at a time; raise MAX_WORKERS only after checking free VRAM.

SLICE="${SLICE:-data/slices/longmemeval_m_full.jsonl}"
OUT="${OUT:-runs/lme_m_full_hf_a100_40gb_seed0}"
SYSTEMS="${SYSTEMS:-b1,b2,b3,b4,controller}"
LIMIT="${LIMIT:-}"
MAX_WORKERS="${MAX_WORKERS:-2}"
QUALITY_PRESET="${QUALITY_PRESET:-max-a100-40gb}"
HF_MODEL="${HF_MODEL:-Qwen/Qwen2.5-7B-Instruct}"
HF_MAX_SEQ_LEN="${HF_MAX_SEQ_LEN:-8192}"
RETRIEVAL_K="${RETRIEVAL_K:-12}"
CONTROLLER_MEMORY_TOP_K="${CONTROLLER_MEMORY_TOP_K:-64}"
RECENCY_MEMORY_TOP_K="${RECENCY_MEMORY_TOP_K:-64}"
EXTRACTION_MAX_NEW_TOKENS="${EXTRACTION_MAX_NEW_TOKENS:-256}"
RELATION_MAX_NEW_TOKENS="${RELATION_MAX_NEW_TOKENS:-128}"
CONTROLLER_RETRIEVAL_NEIGHBOR_WINDOW="${CONTROLLER_RETRIEVAL_NEIGHBOR_WINDOW:-2}"
CONTROLLER_PRIOR_TOP_K="${CONTROLLER_PRIOR_TOP_K:-3}"
CONTROLLER_PRIOR_SIMILARITY_THRESHOLD="${CONTROLLER_PRIOR_SIMILARITY_THRESHOLD:-0.45}"
CONTROLLER_INCLUDE_RAW_USER_CONTEXT="${CONTROLLER_INCLUDE_RAW_USER_CONTEXT:-1}"
CONTROLLER_RETRIEVAL_QUERY_AUGMENTATION="${CONTROLLER_RETRIEVAL_QUERY_AUGMENTATION:-1}"
CONTROLLER_DETERMINISTIC_NUMERIC_SUPERSEDE="${CONTROLLER_DETERMINISTIC_NUMERIC_SUPERSEDE:-1}"
ANSWER_RETRY_ON_UNKNOWN="${ANSWER_RETRY_ON_UNKNOWN:-1}"
CONTROLLER_TEMPORAL_SCAFFOLD="${CONTROLLER_TEMPORAL_SCAFFOLD:-1}"
CONTROLLER_COMPUTATION_ANSWERER="${CONTROLLER_COMPUTATION_ANSWERER:-1}"

export SLICE OUT SYSTEMS LIMIT MAX_WORKERS QUALITY_PRESET HF_MODEL HF_MAX_SEQ_LEN
export RETRIEVAL_K CONTROLLER_MEMORY_TOP_K RECENCY_MEMORY_TOP_K
export EXTRACTION_MAX_NEW_TOKENS RELATION_MAX_NEW_TOKENS
export CONTROLLER_RETRIEVAL_NEIGHBOR_WINDOW CONTROLLER_PRIOR_TOP_K
export CONTROLLER_PRIOR_SIMILARITY_THRESHOLD CONTROLLER_INCLUDE_RAW_USER_CONTEXT
export CONTROLLER_RETRIEVAL_QUERY_AUGMENTATION CONTROLLER_DETERMINISTIC_NUMERIC_SUPERSEDE
export ANSWER_RETRY_ON_UNKNOWN CONTROLLER_TEMPORAL_SCAFFOLD CONTROLLER_COMPUTATION_ANSWERER

bash deploy/run_colab_m4w13_hf_a100_parallel.sh \
  --clean-incomplete \
  "$@"
